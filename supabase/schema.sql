create extension if not exists pgcrypto;

-- ---------------------------------------------------------------- profiles --

create table if not exists public.profiles (
    id              uuid primary key references auth.users (id) on delete cascade,
    display_name    text        not null default 'Người dùng',
    color           bigint      not null default 4292894587,      -- 0xFFE0567B
    invite_code     text        not null unique,
    conversation_id uuid,
    last_seen       timestamptz not null default now(),
    created_at      timestamptz not null default now()
);

-- ----------------------------------------------------------- conversations --

create table if not exists public.conversations (
    id         uuid primary key default gen_random_uuid(),
    member_a   uuid        not null references public.profiles (id) on delete cascade,
    member_b   uuid        not null references public.profiles (id) on delete cascade,
    created_at timestamptz not null default now(),
    constraint conversations_sorted check (member_a < member_b),
    constraint conversations_unique unique (member_a, member_b)
);

do $$
begin
    alter table public.profiles
        add constraint profiles_conversation_fk
        foreign key (conversation_id) references public.conversations (id) on delete set null;
exception
    when duplicate_object then null;
end $$;

-- --------------------------------------------------------------- messages --

create table if not exists public.messages (
    id              bigint generated by default as identity primary key,
    conversation_id uuid        not null references public.conversations (id) on delete cascade,
    sender_id       uuid        not null references public.profiles (id) on delete cascade,
    client_id       uuid        not null,
    body            text        not null check (char_length(body) between 1 and 4000),
    created_at      timestamptz not null default now(),
    read_at         timestamptz,
    constraint messages_client_unique unique (conversation_id, sender_id, client_id)
);

create index if not exists messages_conversation_idx
    on public.messages (conversation_id, id);

-- ---------------------------------------------------------------- helpers --

-- My conversation id, read with definer rights so RLS policies can use it
-- without recursing into profiles.
create or replace function public.my_conversation()
returns uuid
language sql
stable
security definer
set search_path = public
as $$
    select conversation_id from public.profiles where id = auth.uid()
$$;

create or replace function public.generate_invite_code()
returns text
language plpgsql
as $$
declare
    alphabet text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
    code     text;
    attempt  int := 0;
begin
    loop
        code := '';
        for i in 1..6 loop
            code := code || substr(alphabet, floor(random() * length(alphabet))::int + 1, 1);
        end loop;
        exit when not exists (select 1 from public.profiles where invite_code = code);
        attempt := attempt + 1;
        if attempt > 100 then
            raise exception 'Không tạo được mã mời, thử lại sau';
        end if;
    end loop;
    return code;
end $$;

-- Every new auth user (email or anonymous) gets a profile with an invite code.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    insert into public.profiles (id, display_name, invite_code)
    values (
        new.id,
        coalesce(
            nullif(new.raw_user_meta_data ->> 'display_name', ''),
            nullif(split_part(coalesce(new.email, ''), '@', 1), ''),
            'Người dùng'
        ),
        public.generate_invite_code()
    );
    return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
    after insert on auth.users
    for each row execute function public.handle_new_user();

