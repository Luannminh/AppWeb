-- Nhập mã mời của người kia → tạo cuộc trò chuyện và gắn cho cả hai.
create or replace function public.pair_with_code(code text)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
    me    public.profiles;
    mate  public.profiles;
    conv  uuid;
begin
    select * into me from public.profiles where id = auth.uid();
    if me.id is null then
        raise exception 'Chưa có hồ sơ, thử đăng nhập lại';
    end if;
    if me.conversation_id is not null then
        raise exception 'Bạn đã ghép đôi rồi';
    end if;

    select * into mate
      from public.profiles
     where invite_code = upper(trim(code)) and id <> me.id
     limit 1;

    if mate.id is null then
        raise exception 'Mã mời không đúng';
    end if;
    if mate.conversation_id is not null then
        raise exception 'Người này đã ghép đôi với người khác';
    end if;

    insert into public.conversations (member_a, member_b)
    values (least(me.id, mate.id), greatest(me.id, mate.id))
    on conflict (member_a, member_b)
    do update set member_a = excluded.member_a
    returning id into conv;

    update public.profiles
       set conversation_id = conv
     where id in (me.id, mate.id);

    return conv;
end $$;

-- Huỷ ghép đôi: xoá tin nhắn và cuộc trò chuyện của cả hai.
create or replace function public.unpair()
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    conv uuid := public.my_conversation();
begin
    if conv is null then
        return;
    end if;
    update public.profiles set conversation_id = null where conversation_id = conv;
    delete from public.messages where conversation_id = conv;
    delete from public.conversations where id = conv;
end $$;

-- ------------------------------------------------------------------- RLS ---

alter table public.profiles      enable row level security;
alter table public.conversations enable row level security;
alter table public.messages      enable row level security;

drop policy if exists profiles_select on public.profiles;
create policy profiles_select on public.profiles
    for select to authenticated
    using (
        id = auth.uid()
        or (conversation_id is not null and conversation_id = public.my_conversation())
    );

drop policy if exists profiles_update on public.profiles;
create policy profiles_update on public.profiles
    for update to authenticated
    using (id = auth.uid())
    with check (id = auth.uid());

drop policy if exists conversations_select on public.conversations;
create policy conversations_select on public.conversations
    for select to authenticated
    using (auth.uid() in (member_a, member_b));

drop policy if exists messages_select on public.messages;
create policy messages_select on public.messages
    for select to authenticated
    using (conversation_id = public.my_conversation());

drop policy if exists messages_insert on public.messages;
create policy messages_insert on public.messages
    for insert to authenticated
    with check (conversation_id = public.my_conversation() and sender_id = auth.uid());

-- Cần cho "Đã xem": người nhận cập nhật read_at của tin do người kia gửi.
drop policy if exists messages_update on public.messages;
create policy messages_update on public.messages
    for update to authenticated
    using (conversation_id = public.my_conversation())
    with check (conversation_id = public.my_conversation());

